"""60-day brief run: one fire per day, five behaviour scenarios, supply over time.

`uv run python -m goodsim.sixty` writes sim/out/10_sixty_days.png and sim/out/SIXTY_DAYS.md.
Same exact integer protocol as the main run; only the fire length is one day and the horizon 60.
"""
from __future__ import annotations

import time
from dataclasses import replace
from pathlib import Path

import numpy as np

from .analysis import F0, pmap, stack
from .charts import INK2, PALETTE, plt
from .engine import Scenario
from .params import DAY_NS, REC, SEED

DAYS = 60
RUNS = 48
CFG = replace(REC, W=DAY_NS)
SC = [
    Scenario("base", "Steady (λ=1.1)"),
    Scenario("viral", "Viral then fading (λ=1.6 ×8d, 0.9)", lam=((0, 1.6), (8, 0.9))),
    Scenario("cold", "Cold start (8 founders)", founders=8),
    Scenario("decline", "Collapse (λ=0.7 from day 30)", lam=((0, 1.1), (30, 0.7))),
    Scenario("whale", "Whale (50% of every fire)", whale=True),
]


def run(out: Path, runs: int = RUNS, seed: int = SEED) -> dict:
    jobs = [(replace(sc, weeks=DAYS), CFG, seed + i, "all") for sc in SC for i in range(runs)]
    res = pmap(jobs)
    return {sc.name: stack(res[j * runs:(j + 1) * runs]) for j, sc in enumerate(SC)}


SWEEP = [(g0, al) for g0 in (5, 10, 20) for al in (10, 25, 100)]


def sweep(runs: int = 16, seed: int = SEED) -> list:
    sc = replace(SC[2], weeks=DAYS)  # cold start: the case where parameters matter most
    jobs = [(sc, replace(CFG, G0=g0, Gmax=min(CFG.Gmax, 500 * g0), allowance_bps=al), seed + i, "all") for g0, al in SWEEP for i in range(runs)]
    res = pmap(jobs)
    return [stack(res[j * runs:(j + 1) * runs]) for j in range(len(SWEEP))]


def chart(res: dict, out: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.2))
    x = np.arange(1, DAYS + 1)
    for i, sc in enumerate(SC):
        d, c = res[sc.name], PALETTE[i]
        for ax, key, scale in ((axes[0], "supply", 1e6), (axes[1], "max_supply", 1e6), (axes[2], "floor", F0)):
            p10, p50, p90 = np.percentile(d[key] / scale, [10, 50, 90], axis=0)
            ax.fill_between(x, p10, p90, color=c, alpha=0.15, linewidth=0)
            ax.plot(x, p50, color=c, label=sc.label)
    axes[0].set_title("Circulating GOOD (million)")
    axes[1].set_title("Max supply (million): every miss destroys a day's allowance")
    axes[2].set_title("Floor ÷ genesis floor (never decreases)")
    for ax in axes:
        ax.set_xlabel("day")
    axes[0].legend(loc="upper left", fontsize=8)
    fig.suptitle("60 days, one fire per day: median and P10–P90 of 48 paths per scenario", color=INK2)
    fig.tight_layout()
    fig.savefig(out / "10_sixty_days.png", dpi=130)
    plt.close(fig)


def table(res: dict, sw: list, out: Path, secs: float) -> None:
    med = lambda a: float(np.median(a))  # noqa: E731
    rows = ["| Scenario | catches / 60 | longest streak | circulating day 15 / 30 / 60 (M) | max supply day 60 (M) "
            "| destroyed by misses (M) | floor ÷ genesis, day 60 | NEAR to causes |",
            "|---|---|---|---|---|---|---|---|"]
    for sc in SC:
        d = res[sc.name]
        circ = [med(d["supply"][:, t] / 1e6) for t in (14, 29, 59)]
        mx = med(d["max_supply"][:, -1] / 1e6)
        streak = med(d["streak"].max(axis=1))
        rows.append(
            f"| {sc.label} | {med(d['caught'].sum(axis=1)):.0f} | {streak:.0f} | "
            f"{circ[0]:.2f} / {circ[1]:.2f} / {circ[2]:.2f} | {mx:,.1f} | {1000 - mx:,.1f} | "
            f"{med(d['floor'][:, -1] / F0):.1f}× | {med(d['to_causes'][:, -1]):,.0f} |")
    params = (f"goal_start {CFG.G0}, goal_min {CFG.Gmin}, goal_max {CFG.Gmax}, min_gift 1 NEAR, "
              f"fee {CFG.fee_bps / 100:.0f}%, markup {CFG.markup_bps / 100:.0f}%, "
              f"allowance {CFG.allowance_bps / 100:.2f}% of remaining supply per fire")
    (out / "SIXTY_DAYS.md").write_text(
        "# 60-day simulation\n\n"
        f"Generated by `uv run python -m goodsim.sixty` (seed {SEED}, {RUNS} paths per scenario, {secs:.1f} s). "
        f"One fire per day, exact integer protocol model, medians across paths.\n\nParameters: {params}.\n\n"
        + "\n".join(rows) + "\n\n![60 days](10_sixty_days.png)\n\n"
        "## Picking the parameters (cold start, 8 founders, 16 paths per cell)\n\n"
        "| goal_start | allowance per fire | P(day 1 catches) | catches / 60 | longest streak | circulating day 60 (M) "
        "| max supply day 60 (M) | floor ÷ genesis, day 60 |\n|---|---|---|---|---|---|---|---|\n"
        + "\n".join(
            f"| {g0} | {al / 100:.2f}% | {d['caught'][:, 0].mean():.0%} | {med(d['caught'].sum(axis=1)):.0f} | "
            f"{med(d['streak'].max(axis=1)):.0f} | {med(d['supply'][:, -1] / 1e6):.1f} | "
            f"{med(d['max_supply'][:, -1] / 1e6):.0f} | {med(d['floor'][:, -1] / F0):.1f}× |"
            for (g0, al), d in zip(SWEEP, sw)) + "\n")


def main() -> None:
    out = Path(__file__).resolve().parents[2] / "out"
    t0 = time.time()
    res = run(out)
    sw = sweep()
    chart(res, out)
    table(res, sw, out, time.time() - t0)
    print(f"wrote {out}/10_sixty_days.png, SIXTY_DAYS.md in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
