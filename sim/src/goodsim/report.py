"""results.csv (long format) and results.md (tables)."""
from __future__ import annotations

import csv
import math

from .analysis import mc_stats
from .contract import POLICIES
from .scenarios import SCENARIOS, SPEC_NAMES

METRICS = [
    ("initial_minted_supply", "Initial minted supply"),
    ("final_supply_mechanic", "Final supply, mechanic-only"),
    ("final_supply_total", "Final supply, incl. vesting"),
    ("rewards_minted", "Cumulative rewards minted"),
    ("treasury_unlocked", "Treasury unlocked"),
    ("treasury_distributed", "Treasury paid to proposals"),
    ("burned", "Burned"),
    ("reserve_remaining", "Reserve remaining"),
    ("treasury_balance", "Treasury balance (locked+spendable)"),
    ("successes", "Successful epochs (of 8)"),
    ("failures", "Failed epochs"),
    ("no_reserve", "SucceededNoReserve epochs"),
    ("final_streak", "Current streak (day 60)"),
    ("longest_streak", "Longest streak"),
    ("reward_per_participant", "Reward per rewarded participant-epoch (runs with ≥1 reward)"),
    ("reserve_years_left_linear", "Reserve years left (linear extrapolation)"),
]


def fmt(v: float) -> str:
    if isinstance(v, float) and math.isinf(v):
        return "never"
    if isinstance(v, float) and math.isnan(v):
        return "n/a"
    if abs(v) >= 100:
        return f"{v:,.0f}"
    if abs(v - round(v)) < 1e-9:
        return f"{v:.0f}"
    return f"{v:,.2f}"


def years_cell(policy: str, v: float) -> str:
    if policy == "C":
        return "never (geometric)"
    return fmt(v)


def write_csv(results, path):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "policy", "metric", "mean_path", "mc_mean", "mc_p10", "mc_p90"])
        for scen in SCENARIOS:
            for pol in POLICIES:
                r = results[scen][pol]
                for key, _ in METRICS:
                    m, lo, hi = mc_stats(r["mc"], key)
                    w.writerow([scen, pol, key, repr(float(r["mean_path"][key])), repr(m), repr(lo), repr(hi)])


def cell(r, key, policy="B"):
    mp = r["mean_path"][key]
    m, lo, hi = mc_stats(r["mc"], key)
    if key == "reserve_years_left_linear":
        if policy == "C":
            return "never (geometric)"
        return f"{fmt(mp)} · {fmt(m)} [{fmt(lo)}–{fmt(hi)}]"
    if key == "initial_minted_supply":
        return fmt(mp)
    return f"{fmt(mp)} · {fmt(m)} [{fmt(lo)}–{fmt(hi)}]"


def scenario_table(results, names, policy="B"):
    lines = ["| Metric (GOOD unless count) | " + " | ".join(names) + " |",
             "|---|" + "---:|" * len(names)]
    for key, label in METRICS:
        lines.append(f"| {label} | " + " | ".join(cell(results[n][policy], key, policy) for n in names) + " |")
    return "\n".join(lines)


def policy_table(results):
    keys = ["successes", "rewards_minted", "reward_per_participant", "burned", "final_supply_mechanic",
            "reserve_remaining", "reserve_years_left_linear"]
    head = ["scenario", "policy", "successes", "rewards minted", "reward/participant-epoch", "burned",
            "final supply (mech.)", "reserve remaining", "reserve years left"]
    lines = ["| " + " | ".join(head) + " |", "|---|---|" + "---:|" * (len(head) - 2)]
    for scen in SCENARIOS:
        for pol, (pname, _) in POLICIES.items():
            r = results[scen][pol]
            cells = []
            for k in keys:
                m, _, _ = mc_stats(r["mc"], k)
                cells.append(years_cell(pol, m) if k == "reserve_years_left_linear" else fmt(m))
            lines.append(f"| {scen} | {pol} {pname} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def k_table(ks):
    cols = list(SPEC_NAMES) + [s + "_fixed_ratio" for s in SPEC_NAMES]
    lines = ["| k | " + " | ".join(SPEC_NAMES) + " | " + " | ".join(f"{s} (fixed deeds/person)" for s in SPEC_NAMES) + " |",
             "|---:|" + "---:|" * len(cols)]
    show = [k for i, k in enumerate(ks["grid"]) if i % 4 == 0 or not math.isfinite(k)]
    for k in show:
        row = ks["table"][k]
        kk = "∞ (Poisson)" if not math.isfinite(k) else f"{k:g}"
        lines.append(f"| {kk} | " + " | ".join(f"{row[s]:.2f}" for s in cols) + " |")
    return "\n".join(lines)


def write_md(results, ks, flood, ring, exhaust, depletion, p, cfg, path):
    adv = [n for n in SCENARIOS if n not in SPEC_NAMES]
    per = ks["per_scenario_k"]
    bk = ks["best_k"]
    best_row = ks["table"][bk]
    md = []
    md.append("# GOODCOIN simulation results\n")
    md.append(f"Generated by `uv run python -m goodsim` · seed {cfg['seed']} · {cfg['runs']:,} MC runs · "
              f"NegBin dispersion k={cfg['k']:g} · horizon {cfg['horizon']} days "
              f"({p.epochs_settled_by(cfg['horizon'])} settled epochs) · spend_rate={p.spend_rate} · "
              f"claim_rate={p.claim_rate}\n")
    md.append("Cell format: `mean-path · MC mean [P10–P90]`. Mean path = every week exactly at the scenario "
              "means. All GOOD amounts are token units.\n")
    md.append("## 1. Spec scenarios — policy B (streak multiplier, default)\n")
    md.append(scenario_table(results, list(SPEC_NAMES)))
    md.append("\n## 2. Adversarial scenarios — policy B\n")
    md.append(scenario_table(results, adv))
    md.append("\n## 3. Policy comparison (MC means)\n")
    md.append(policy_table(results))
    md.append("\n## 4. Dispersion sensitivity: expected successes /8 vs k\n")
    md.append(f"Spec-stated counts (assumptions, not targets): optimistic 8, base 6, pessimistic 2.\n")
    md.append(k_table(ks))
    md.append(f"\nBest joint fit k = {bk:g} → ({', '.join(f'{best_row[s]:.2f}' for s in SPEC_NAMES)}), "
              f"SSE {ks['best_sse']:.2f}. k reproducing each count alone: "
              + ", ".join(f"{s} {('k≈%.2f' % per[s]) if per[s] else 'none'}" for s in SPEC_NAMES) + ". "
              + "Max achievable over the grid: "
              + ", ".join(f"{s} {max(ks['table'][k][s] for k in ks['grid']):.2f}" for s in SPEC_NAMES)
              + ". No single k reproduces 8/6/2; base is capped below 6 even at Poisson because "
              "deeds-per-person noise alone makes P(deeds ≥ 100 | 55 people) < 1. "
              "Right-hand columns remove that noise (deeds = floor(P·μd/μp)) for comparison.\n")
    a_mint = 55 * p.base_reward
    burn1 = p.treasury_genesis * p.burn_bps / 1e4
    md.append("## 4b. Key ratio (base, first epoch)\n")
    md.append(f"- One failure burns {burn1:,.0f} GOOD; one success mints {a_mint:,.0f} (A, or B at streak 0) to "
              f"{a_mint * 2:,.0f} (B at cap). Burn/mint = {burn1 / a_mint:.0f}x (A) to {burn1 / (2 * a_mint):.0f}x (B max).\n")
    md.append("## 5. Duplicate-submission flood (per epoch, base honest load 110 approved deeds)\n")
    md.append("| flood subs | attacker accts (5 subs/epoch cap) | attestations, exact dups | attestations, byte-altered dups | honest attestations | attestors needed (50/epoch cap) | reward impact |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|")
    for r in flood:
        md.append(f"| {r['flood_subs_per_epoch']:,} | {r['attacker_accounts_needed']:,} | 0 | "
                  f"{r['altered_dup_attestations']:,} | {r['honest_attestations']:,.0f} | "
                  f"{r['attestors_needed_at_cap']:,} | 0 |")
    md.append("\n## 6. Fake-attestation ring (pessimistic scenario)\n")
    md.append(f"- Mean path per failing epoch: {ring['puppets_per_epoch']:.0f} sock-puppets and "
              f"{ring['fakes_per_epoch']:.0f} fake approved deeds flip it to success; needs "
              f"{ring['fakes_per_epoch'] * 3:.0f} ring attestations → ring of ≥{ring['ring_size_needed']} "
              f"earned attestors (50 attestations/epoch cap).")
    md.append(f"- MC (k={cfg['k']:g}): mean {ring['mc_puppets_mean']:.0f} puppet-epochs and "
              f"{ring['mc_fakes_mean']:.0f} fake deeds over 8 epochs to force 8/8 successes.")
    md.append(f"- Over 8 epochs (policy B, mean path): sock-puppets extract {ring['puppet_reward_8ep']:,.1f} GOOD; "
              f"honest participants receive {ring['honest_rewards_8ep_with_ring']:,.1f} GOOD they otherwise would not; "
              f"burn avoided {ring['burn_avoided_8ep']:,.0f} GOOD; treasury unlocked {ring['unlocked_with_ring']:,.0f} GOOD "
              "(puppets are also eligible voters for it).")
    md.append("- Max reward extraction per epoch with unlimited puppets, by ring size r "
              "(capacity = floor(50r/3) fake approvals, reward capped at 50 GOOD): "
              + ", ".join(f"r={r}: {c} deeds → {ring['max_extraction_per_epoch'][r]:,.0f} GOOD"
                          for r, c in ring["ring_capacity_fakes_per_epoch"].items())
              + ". Approved puppets become earned attestors next epoch, so capacity compounds.\n")
    md.append("## 7. Reserve exhaustion stress (optimistic mean participation, reward × X)\n")
    for pol, ex in exhaust.items():
        md.append(f"- Policy {pol}: exhausts within 60 days at X ≥ {ex['60 days']['X']:,.0f} "
                  f"(closed form {ex['60 days']['X_analytic']:,.0f}); within 10 years "
                  f"({ex['10 years']['epochs']} epochs) at X ≥ {ex['10 years']['X']:,.1f}.")
    md.append(f"- Policy C never exhausts: remaining after 10 years of successes = "
              f"{exhaust['B']['C_remaining_10y']:,.0f} GOOD.\n")
    md.append("## 8. Treasury depletion (every epoch fails)\n")
    md.append(f"- Locked treasury halves after ln(0.5)/ln(0.999) = {depletion['epochs_analytic']:.1f} epochs "
              f"= {depletion['years_analytic']:.2f} years (simulated: {depletion['epochs_simulated']} epochs = "
              f"{depletion['years_simulated']:.2f} years).")
    md.append(f"- 60 days all-fail burns {depletion['burned_60d_all_fail']:,.0f} GOOD "
              f"({depletion['burned_60d_all_fail'] / p.treasury_genesis:.3%} of treasury).\n")
    open(path, "w").write("\n".join(md))
